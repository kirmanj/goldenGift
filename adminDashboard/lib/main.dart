Future<void> main() async {
  // Never a blank page: a startup failure is logged and shown (SRS §8).
  await runZonedGuarded(_start, (error, stack) {
    // ignore: avoid_print
    print('Golden Gift Admin error: ${error.runtimeType}: $error\n$stack');
  });
}

Future<void> _start() async {
  WidgetsFlutterBinding.ensureInitialized();
  try {
    await _init();
  } catch (e, s) {
    // ignore: avoid_print
    print('Golden Gift Admin could not start: ${e.runtimeType}: $e\n$s');
    runApp(_StartupError(message: '$e'));
  }
}

Future<void> _init() async {
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  // App Check (SRS §8, Phase 10) — needs a reCAPTCHA Enterprise site key:
  // `flutter build web --dart-define=RECAPTCHA_SITE_KEY=…`. Without one the
  // dashboard runs unprotected (fine until ENFORCE_APP_CHECK is switched on).
  if (AppEnv.recaptchaSiteKey.isNotEmpty) {
    try {
      await FirebaseAppCheck.instance.activate(webProvider: ReCaptchaEnterpriseProvider(AppEnv.recaptchaSiteKey));
    } catch (_) {}
  }
  if (AppEnv.useEmulator) {
    final host = AppEnv.emulatorHost;
    FirebaseFirestore.instance.useFirestoreEmulator(host, AppEnv.firestorePort);
    await FirebaseAuth.instance.useAuthEmulator(host, AppEnv.authPort);
    await FirebaseStorage.instance.useStorageEmulator(host, AppEnv.storagePort);
    FirebaseFunctions.instanceFor(region: AppEnv.functionsRegion).useFunctionsEmulator(host, AppEnv.functionsPort);
  }
  final prefs = await SharedPreferences.getInstance();
  runApp(ProviderScope(
    overrides: [sharedPreferencesProvider.overrideWithValue(prefs)],
    child: const GoldenGiftAdminApp(),
  ));
}

class _StartupError extends StatelessWidget {
  const _StartupError({required this.message});
  final String message;

  @override
  Widget build(BuildContext context) => MaterialApp(
        debugShowCheckedModeBanner: false,
        theme: AdminTheme.light(),
        home: Scaffold(
          body: Center(
            child: Padding(
              padding: const EdgeInsets.all(24),
              child: Column(mainAxisSize: MainAxisSize.min, children: [
                const Icon(Icons.error_outline, size: 40),
                const SizedBox(height: 12),
                const Text('Golden Gift Admin could not start. Reload the page; if it keeps happening, send this to support:'),
                const SizedBox(height: 8),
                SelectableText(message, textAlign: TextAlign.center),
              ]),
            ),
          ),
        ),
      );
}


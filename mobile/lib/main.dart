Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  await configureFirebase();
  final prefs = await SharedPreferences.getInstance();
  runApp(
    ProviderScope(
      overrides: [sharedPreferencesProvider.overrideWithValue(prefs)],
      child: const GoldenGiftApp(),
    ),
  );
}

/// App Check (SRS §8 Security, Phase 10): Play Integrity / App Attest (with
/// DeviceCheck fallback) in release builds, the debug provider in debug builds
/// and on the emulators (register the printed debug token in the Firebase
/// console). Web only with a reCAPTCHA Enterprise key. Never fatal: functions
/// enforce it only once ENFORCE_APP_CHECK is switched on.
Future<void> activateAppCheck() async {
  if (kIsWeb && AppEnv.recaptchaSiteKey.isEmpty) return;
  const debug = kDebugMode || AppEnv.useEmulator;
  try {
    await FirebaseAppCheck.instance.activate(
      webProvider: kIsWeb ? ReCaptchaEnterpriseProvider(AppEnv.recaptchaSiteKey) : null,
      androidProvider: debug ? AndroidProvider.debug : AndroidProvider.playIntegrity,
      appleProvider: debug ? AppleProvider.debug : AppleProvider.appAttestWithDeviceCheckFallback,
    );
  } catch (e) {
    if (kDebugMode) debugPrint('App Check activation failed: $e');
  }
}

/// Emulators (when USE_EMULATOR), offline persistence and Crashlytics. Also used by
/// integration_test/ so tests run the same setup as the app.
Future<void> configureFirebase() async {
  if (AppEnv.useEmulator) {
    final host = AppEnv.emulatorHost;
    FirebaseFirestore.instance.useFirestoreEmulator(host, AppEnv.firestorePort);
    await FirebaseAuth.instance.useAuthEmulator(host, AppEnv.authPort);
    await FirebaseStorage.instance.useStorageEmulator(host, AppEnv.storagePort);
    FirebaseFunctions.instanceFor(region: AppEnv.functionsRegion)
        .useFunctionsEmulator(host, AppEnv.functionsPort);
  }

  await activateAppCheck();

  // Offline persistence: catalogue screens render from cache (SRS §4.8).
  FirebaseFirestore.instance.settings = const Settings(
    persistenceEnabled: true,
    cacheSizeBytes: Settings.CACHE_SIZE_UNLIMITED,
  );

  // Crashlytics has no web support; debug builds don't report.
  if (!kIsWeb) {
    final crashlytics = FirebaseCrashlytics.instance;
    await crashlytics.setCrashlyticsCollectionEnabled(!kDebugMode);
    FlutterError.onError = crashlytics.recordFlutterFatalError;
    PlatformDispatcher.instance.onError = (error, stack) {
      unawaited(crashlytics.recordError(error, stack, fatal: true));
      return true;
    };
  }
}

class GoldenGiftApp extends ConsumerWidget {
  const GoldenGiftApp({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final locale = ref.watch(localeProvider);
    final router = ref.watch(appRouterProvider);
    return MaterialApp.router(
      title: 'Golden Gift',
      debugShowCheckedModeBanner: false,
      locale: locale,
      theme: AppTheme.lightTheme(locale),
      darkTheme: AppTheme.darkTheme(locale),
      themeMode: ref.watch(themeModeProvider),
      supportedLocales: AppLocalizations.supportedLocales,
      localizationsDelegates: const [
        AppLocalizations.delegate,
        // Before the Global* delegates: Kurdish (ckb) borrows Arabic system
        // strings and RTL direction, which Flutter doesn't ship for ckb.
        ...KurdishFallbackLocalizations.delegates,
        GlobalMaterialLocalizations.delegate,
        GlobalWidgetsLocalizations.delegate,
        GlobalCupertinoLocalizations.delegate,
      ],
      routerConfig: router,
      builder: (context, child) => MaxWidthFrame(child: child ?? const SizedBox.shrink()),
    );
  }
}
